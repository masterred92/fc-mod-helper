"""Timestamped zip backups of Career saves, Mod Manager state and FIFAModData.

Each zip has a manifest.json (what was copied from where, file hashes) and one
top-level folder per component. Restore always snapshots the current state first.
"""

from __future__ import annotations

import datetime as _dt
import hashlib
import json
import os
import re
import shutil
import zipfile
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

from fcmh import __version__
from fcmh.ui import UI

COMPONENTS = {
    "saves": ("settings_dir", "Career saves, squads and profile settings"),
    "fmm": ("fmm_dir", "FIFA Mod Manager folder (profiles, mod list, config)"),
    "moddata": ("fifamoddata_dir", "FIFAModData (generated by Mod Manager, can be large)"),
}
DEFAULT_COMPONENTS = ("saves", "fmm")
MANIFEST = "manifest.json"
NAME_RE = re.compile(r"^fcmh-backup-(\d{8}-\d{6})(?:-[A-Za-z0-9_-]+)?\.zip$")


class BackupError(Exception):
    pass


@dataclass
class BackupInfo:
    path: Path
    created: str
    label: str
    components: list[str]
    files: int
    size: int


def _safe_label(label: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "-", label).strip("-")
    return cleaned[:40]


def _hash(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def create_backup(sources: dict[str, Path], dest_dir: Path, *, label: str = "", game: str = "",
                  build: str = "", now: _dt.datetime | None = None) -> Path:
    """sources maps component name -> folder. Missing folders are recorded as skipped."""
    if not sources:
        raise BackupError("Nothing to back up: no component folders are configured")
    now = now or _dt.datetime.now()
    stamp = now.strftime("%Y%m%d-%H%M%S")
    name = f"fcmh-backup-{stamp}" + (f"-{_safe_label(label)}" if label else "") + ".zip"
    dest_dir.mkdir(parents=True, exist_ok=True)
    target = dest_dir / name
    counter = 1
    while target.exists():
        target = dest_dir / name.replace(".zip", f"_{counter}.zip")
        counter += 1

    manifest = {
        "tool": "fc-mod-helper", "tool_version": __version__, "created": now.isoformat(timespec="seconds"),
        "label": label, "game": game, "build": build, "components": {},
    }
    tmp = target.with_suffix(".zip.partial")
    try:
        with zipfile.ZipFile(tmp, "w", compression=zipfile.ZIP_DEFLATED, allowZip64=True) as archive:
            for component, folder in sources.items():
                entry = {"source": str(folder), "status": "ok", "files": []}
                if not folder or not Path(folder).is_dir():
                    entry["status"] = "missing"
                    manifest["components"][component] = entry
                    continue
                folder = Path(folder)
                for root, dirs, files in os.walk(folder):
                    dirs.sort()
                    for filename in sorted(files):
                        full = Path(root) / filename
                        rel = full.relative_to(folder).as_posix()
                        archive.write(full, f"{component}/{rel}")
                        entry["files"].append({"path": rel, "size": full.stat().st_size, "sha256": _hash(full)})
                manifest["components"][component] = entry
            archive.writestr(MANIFEST, json.dumps(manifest, indent=2))
        os.replace(tmp, target)
    except BaseException:
        if tmp.exists():
            tmp.unlink()
        raise
    return target


def read_manifest(path: Path) -> dict:
    try:
        with zipfile.ZipFile(path) as archive:
            return json.loads(archive.read(MANIFEST))
    except (KeyError, zipfile.BadZipFile, json.JSONDecodeError) as exc:
        raise BackupError(f"{path.name} is not a valid fcmh backup: {exc}") from exc


def list_backups(dest_dir: Path) -> list[BackupInfo]:
    if not dest_dir.is_dir():
        return []
    found = []
    for path in sorted(dest_dir.glob("fcmh-backup-*.zip")):
        try:
            manifest = read_manifest(path)
        except BackupError:
            continue
        comps = [c for c, e in manifest.get("components", {}).items() if e.get("status") == "ok"]
        files = sum(len(e.get("files", [])) for e in manifest.get("components", {}).values())
        found.append(BackupInfo(path, manifest.get("created", ""), manifest.get("label", ""), comps,
                                files, path.stat().st_size))
    found.sort(key=lambda b: b.created)
    return found


def find_backup(dest_dir: Path, name: str) -> Path:
    candidate = Path(name)
    if candidate.is_file():
        return candidate
    for info in list_backups(dest_dir):
        if info.path.name == name or info.path.stem == name:
            return info.path
    raise BackupError(f"No backup named {name} in {dest_dir}. See `fcmh backup list`.")


def _safe_members(archive: zipfile.ZipFile, component: str) -> list[tuple[zipfile.ZipInfo, PurePosixPath]]:
    members = []
    prefix = f"{component}/"
    for info in archive.infolist():
        if not info.filename.startswith(prefix) or info.is_dir():
            continue
        rel = PurePosixPath(info.filename[len(prefix):])
        if rel.is_absolute() or ".." in rel.parts or (rel.parts and ":" in rel.parts[0]):
            raise BackupError(f"Unsafe path in backup: {info.filename}")
        members.append((info, rel))
    return members


def verify_backup(path: Path) -> list[str]:
    """Returns a list of problems (empty if the zip matches its manifest)."""
    problems = []
    manifest = read_manifest(path)
    with zipfile.ZipFile(path) as archive:
        names = set(archive.namelist())
        for component, entry in manifest.get("components", {}).items():
            for item in entry.get("files", []):
                member = f"{component}/{item['path']}"
                if member not in names:
                    problems.append(f"missing {member}")
                    continue
                digest = hashlib.sha256(archive.read(member)).hexdigest()
                if digest != item.get("sha256"):
                    problems.append(f"checksum mismatch {member}")
    return problems


def restore_backup(path: Path, targets: dict[str, Path], dest_dir: Path, ui: UI, *,
                   components: list[str] | None = None, dry_run: bool = False,
                   game: str = "", build: str = "") -> dict:
    """targets maps component -> folder to restore into. Takes a safety backup first."""
    manifest = read_manifest(path)
    available = [c for c, e in manifest.get("components", {}).items() if e.get("status") == "ok"]
    wanted = components or available
    unknown = [c for c in wanted if c not in available]
    if unknown:
        raise BackupError(f"Backup {path.name} has no component(s): {', '.join(unknown)}")
    missing_targets = [c for c in wanted if not targets.get(c)]
    if missing_targets:
        raise BackupError(f"No restore folder configured for: {', '.join(missing_targets)}")

    problems = verify_backup(path)
    if problems:
        raise BackupError(f"Backup failed verification ({len(problems)} problems), e.g. {problems[0]}")

    ui.out(f"Restoring {', '.join(wanted)} from {path.name} (created {manifest.get('created')})")
    for c in wanted:
        ui.out(f"  {c}: {len(manifest['components'][c]['files'])} files -> {targets[c]}")
    if dry_run:
        ui.out("Dry run: nothing changed. A safety backup of the current state would be taken first.")
        return {"restored": [], "safety_backup": None}
    ui.out("Close FC, the EA app and Mod Manager before continuing.")
    if not ui.confirm("Replace these folders with the backup? A safety backup is taken first."):
        ui.out("Cancelled.")
        return {"restored": [], "safety_backup": None}

    safety = create_backup({c: targets[c] for c in wanted}, dest_dir, label="pre-restore", game=game, build=build)
    ui.out(f"Safety backup of current state: {safety}")

    with zipfile.ZipFile(path) as archive:
        for component in wanted:
            target = Path(targets[component])
            members = _safe_members(archive, component)
            staging = target.parent / f".{target.name}.fcmh-restore"
            if staging.exists():
                shutil.rmtree(staging)
            staging.mkdir(parents=True)
            for info, rel in members:
                out = staging.joinpath(*rel.parts)
                out.parent.mkdir(parents=True, exist_ok=True)
                with archive.open(info) as src, open(out, "wb") as dst:
                    shutil.copyfileobj(src, dst)
            if target.exists():
                shutil.rmtree(target)
            os.replace(staging, target)
            ui.out(f"  restored {component}")
    return {"restored": wanted, "safety_backup": safety}
